-- Initial provisioning only. IF NOT EXISTS preserves existing records and definitions.
-- Standard-table PK/UNIQUE/FK declarations document relationships; the writer
-- must enforce them. Do not add a migration ledger (exactly 11 base tables).
USE ROLE HACKATHON_OWNER;
USE DATABASE HACKATHON_DB;
USE SCHEMA APP;
ALTER SESSION SET TIMEZONE = 'UTC';

CREATE TABLE IF NOT EXISTS USERS (
    USER_ID VARCHAR(64) NOT NULL,
    AUTH_SUBJECT VARCHAR(512) NOT NULL,
    DISPLAY_NAME VARCHAR(256),
    EMAIL VARCHAR(320) NOT NULL,
    PASSWORD_HASH VARCHAR(512) NOT NULL,
    TIMEZONE VARCHAR(128) NOT NULL DEFAULT 'America/Indiana/Indianapolis',
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    DELETED_AT TIMESTAMP_TZ,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_AUTH UNIQUE (AUTH_SUBJECT),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS USER_PREFERENCES (
    USER_ID VARCHAR(64) NOT NULL,
    PREFERENCE_TEXT VARCHAR(8000) NOT NULL DEFAULT '',
    INTEREST_TAG_IDS ARRAY NOT NULL DEFAULT ARRAY_CONSTRUCT(),
    EXCLUDED_TAG_IDS ARRAY NOT NULL DEFAULT ARRAY_CONSTRUCT(),
    FOLLOWED_ONLY BOOLEAN NOT NULL DEFAULT FALSE,
    FREE_ONLY BOOLEAN NOT NULL DEFAULT FALSE,
    HORIZON_DAYS NUMBER(3,0) NOT NULL DEFAULT 30,
    VERSION NUMBER(38,0) NOT NULL DEFAULT 1,
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_USER_PREFERENCES PRIMARY KEY (USER_ID),
    CONSTRAINT FK_PREFERENCES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS CLUBS (
    CLUB_ID VARCHAR(64) NOT NULL,
    SLUG VARCHAR(128) NOT NULL,
    NAME VARCHAR(256) NOT NULL,
    DESCRIPTION VARCHAR(8000),
    CAMPUS VARCHAR(128) NOT NULL DEFAULT 'purdue-west-lafayette',
    WEBSITE_URL VARCHAR(2048),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CLUBS PRIMARY KEY (CLUB_ID),
    CONSTRAINT UQ_CLUBS_SLUG UNIQUE (SLUG)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS INSTAGRAM_ACCOUNTS (
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    USERNAME VARCHAR(30) NOT NULL,
    INSTAGRAM_USER_ID VARCHAR(128),
    CLUB_ID VARCHAR(64),
    DISPLAY_NAME VARCHAR(256),
    BIO VARCHAR(8000),
    PROFILE_URL VARCHAR(2048) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    INGESTION_STATUS VARCHAR(32) NOT NULL DEFAULT 'pending',
    LAST_ATTEMPT_AT TIMESTAMP_TZ,
    LAST_SUCCESS_AT TIMESTAMP_TZ,
    NEXT_RETRY_AT TIMESTAMP_TZ,
    LAST_ERROR VARCHAR(8000),
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_INSTAGRAM_ACCOUNTS PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UQ_INSTAGRAM_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_INSTAGRAM_EXTERNAL_ID UNIQUE (INSTAGRAM_USER_ID),
    CONSTRAINT FK_ACCOUNT_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS(CLUB_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS USER_FOLLOWS (
    USER_ID VARCHAR(64) NOT NULL,
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_USER_FOLLOWS PRIMARY KEY (USER_ID, ACCOUNT_ID),
    CONSTRAINT FK_FOLLOW_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_FOLLOW_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES INSTAGRAM_ACCOUNTS(ACCOUNT_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS TAGS (
    TAG_ID VARCHAR(64) NOT NULL,
    SLUG VARCHAR(128) NOT NULL,
    LABEL VARCHAR(128) NOT NULL,
    CATEGORY VARCHAR(32) NOT NULL,
    DESCRIPTION VARCHAR(2000),
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_TAGS PRIMARY KEY (TAG_ID),
    CONSTRAINT UQ_TAGS_SLUG UNIQUE (SLUG)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS CLUB_TAGS (
    CLUB_ID VARCHAR(64) NOT NULL,
    TAG_ID VARCHAR(64) NOT NULL,
    SOURCE VARCHAR(32) NOT NULL DEFAULT 'manual',
    CONFIDENCE FLOAT,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CLUB_TAGS PRIMARY KEY (CLUB_ID, TAG_ID),
    CONSTRAINT FK_CLUB_TAG_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS(CLUB_ID),
    CONSTRAINT FK_CLUB_TAG_TAG FOREIGN KEY (TAG_ID) REFERENCES TAGS(TAG_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS POSTS (
    POST_ID VARCHAR(64) NOT NULL,
    SHORTCODE VARCHAR(128) NOT NULL,
    INSTAGRAM_MEDIA_ID VARCHAR(128),
    ACCOUNT_ID VARCHAR(64) NOT NULL,
    PERMALINK VARCHAR(2048) NOT NULL,
    POSTED_AT TIMESTAMP_TZ NOT NULL,
    CAPTION VARCHAR(16777216),
    MEDIA_TYPE VARCHAR(32) NOT NULL DEFAULT 'image',
    MEDIA_URLS ARRAY NOT NULL DEFAULT ARRAY_CONSTRUCT(),
    OCR_TEXT VARCHAR(16777216),
    RAW_PAYLOAD VARIANT,
    CONTENT_HASH VARCHAR(64) NOT NULL,
    EXTRACTION_STATUS VARCHAR(32) NOT NULL DEFAULT 'pending',
    EXTRACTION_VERSION VARCHAR(256),
    EXTRACTED_PAYLOAD VARIANT,
    ATTEMPT_COUNT NUMBER(10,0) NOT NULL DEFAULT 0,
    LEASE_EXPIRES_AT TIMESTAMP_TZ,
    LAST_ERROR VARCHAR(8000),
    INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    SOURCE_SEEN_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    DELETED_AT TIMESTAMP_TZ,
    CONSTRAINT PK_POSTS PRIMARY KEY (POST_ID),
    CONSTRAINT UQ_POSTS_SHORTCODE UNIQUE (SHORTCODE),
    CONSTRAINT UQ_POSTS_EXTERNAL_ID UNIQUE (INSTAGRAM_MEDIA_ID),
    CONSTRAINT FK_POST_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES INSTAGRAM_ACCOUNTS(ACCOUNT_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS EVENTS (
    EVENT_ID VARCHAR(64) NOT NULL,
    DEDUPE_KEY VARCHAR(64) NOT NULL,
    CLUB_ID VARCHAR(64) NOT NULL,
    TITLE VARCHAR(512) NOT NULL,
    DESCRIPTION VARCHAR(16000),
    START_AT TIMESTAMP_TZ,
    END_AT TIMESTAMP_TZ,
    LOCAL_START_DATE DATE,
    EVENT_TIMEZONE VARCHAR(128) NOT NULL DEFAULT 'America/Indiana/Indianapolis',
    DATE_PRECISION VARCHAR(32) NOT NULL DEFAULT 'unknown',
    LOCATION_NAME VARCHAR(512),
    LOCATION_ADDRESS VARCHAR(2048),
    LOCATION_URL VARCHAR(2048),
    REGISTRATION_URL VARCHAR(2048),
    PRICE_AMOUNT NUMBER(12,2),
    PRICE_CURRENCY VARCHAR(3) NOT NULL DEFAULT 'USD',
    IS_FREE BOOLEAN,
    STATUS VARCHAR(32) NOT NULL DEFAULT 'draft',
    CONFIDENCE FLOAT,
    EXTRACTION_VERSION VARCHAR(256),
    SEARCH_TEXT VARCHAR(16000) NOT NULL DEFAULT '',
    REVISION NUMBER(38,0) NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_EVENTS PRIMARY KEY (EVENT_ID),
    CONSTRAINT UQ_EVENTS_DEDUPE UNIQUE (DEDUPE_KEY),
    CONSTRAINT FK_EVENT_CLUB FOREIGN KEY (CLUB_ID) REFERENCES CLUBS(CLUB_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1 CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS EVENT_TAGS (
    EVENT_ID VARCHAR(64) NOT NULL,
    TAG_ID VARCHAR(64) NOT NULL,
    SOURCE VARCHAR(32) NOT NULL DEFAULT 'extracted',
    CONFIDENCE FLOAT,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_EVENT_TAGS PRIMARY KEY (EVENT_ID, TAG_ID),
    CONSTRAINT FK_EVENT_TAG_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(EVENT_ID),
    CONSTRAINT FK_EVENT_TAG_TAG FOREIGN KEY (TAG_ID) REFERENCES TAGS(TAG_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;

CREATE TABLE IF NOT EXISTS EVENT_SOURCES (
    EVENT_ID VARCHAR(64) NOT NULL,
    POST_ID VARCHAR(64) NOT NULL,
    SOURCE_EVENT_KEY VARCHAR(64) NOT NULL,
    IS_PRIMARY BOOLEAN NOT NULL DEFAULT FALSE,
    EVIDENCE VARIANT NOT NULL,
    SOURCE_CONTENT_HASH VARCHAR(64) NOT NULL,
    EXTRACTION_VERSION VARCHAR(256) NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_EVENT_SOURCES PRIMARY KEY (EVENT_ID, POST_ID),
    CONSTRAINT UQ_SOURCE_OCCURRENCE UNIQUE (POST_ID, SOURCE_EVENT_KEY),
    CONSTRAINT FK_SOURCE_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(EVENT_ID),
    CONSTRAINT FK_SOURCE_POST FOREIGN KEY (POST_ID) REFERENCES POSTS(POST_ID)
) DATA_RETENTION_TIME_IN_DAYS = 1;
